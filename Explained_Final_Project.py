"""---
## موديل 1: التدريب والتقييم — CatBoost vs LightGBM (Regression)

الـ target هنا رقم مستمر (`active_power`)، يعني احنا في عالم الـ **Regression**. معنى إننا "كسبنا" هنا = الرقم اللي الموديل توقعه قريب من الرقم الحقيقي، مش "صح/غلط" زي التصنيف.

### قبل ما نشغّل: هنقيّم بإيه؟ (اشرحلي زي ما انا مش فاهم حاجة)

هنستخدم 3 مقاييس، كل واحد بيحكي جزء مختلف من القصة:

- **MAE (Mean Absolute Error):** لو الموديل توقع 500 والحقيقي كان 520، يبقى الغلط هنا 20. الـ MAE هو **متوسط** كل الغلطات دي (كلها موجبة، مفيش سالب). ميزته إنه **سهل الفهم** لأنه بنفس وحدة الـ target نفسه (يعني لو `active_power` بالـ kW، الـ MAE هيبقى بالـ kW برضو). لو MAE = 15 معناه "في المتوسط، توقع الموديل بعيد عن الحقيقة بمقدار 15 وحدة".
- **RMSE (Root Mean Squared Error):** زي الـ MAE، بس **بيربّع الغلط الأول قبل المتوسط وبعدين بياخد الجذر**. النتيجة: أي غلطة **كبيرة جدًا** (outlier prediction) بتتعاقب أكتر بكتير من الغلطات الصغيرة. لو RMSE أكبر بكتير من MAE، ده معناه فيه شوية توقعات غلط جدًا (مش غلط بسيط منتشر على الكل).
- **R² (R-squared):** ده مش وحدة زي الاتنين اللي فوق، ده **نسبة من صفر لواحد** (ممكن يبقى سالب لو الموديل وحش جدًا). بيقولك: "الموديل قدر يفسّر كام % من التغيّر (variance) اللي حصل في `active_power`؟". R² = 0.95 معناه الموديل فسّر 95% من التغير في الطاقة المنتجة اعتمادًا على الفيتشرز (irradiance, temp, ...)، والـ 5% الباقيين ممكن يكونوا noise أو عوامل مش موجودة في الداتا.

**القاعدة البسيطة:** MAE و RMSE **كل ما قلّوا كان أحسن**، R² **كل ما قرب من 1 كان أحسن**.

**شرح الخلية:** تدريب موديل CatBoost Regressor على بيانات موديل 1 لتوقع active_power، ثم استخدامه لعمل تنبؤات على بيانات الاختبار.
"""

