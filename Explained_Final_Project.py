"""### الخطوة 2: الحل — Blocked Time Split لكل (device × week)

**شرح الخلية:** تعريف دالة time_block_split اللي بتقسم كل مجموعة (جهاز × أسبوع) زمنيًا: أول 80% من الصفوف يروحوا Train والـ 20% الباقيين يروحوا Test، عشان الـ train يسبق الـ test زمنيًا دايمًا. بعدين تطبيق التقسيم ده على كل جهاز وكل أسبوع على حدة وتجميع النتائج في train_df وtest_df.
"""

def time_block_split(group, train_frac=0.8):
    """Chronological 80/20 split within one group (device, week).
    First `train_frac` of the rows (already sorted by time) go to train,
    the last remaining rows go to test -> train always precedes test.
    """
    n = len(group)
    cut = int(np.floor(n * train_frac))
