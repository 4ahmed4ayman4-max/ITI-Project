pred_lgbm_m1 = lgbm_reg_m1.predict(X_test_m1)

"""**شرح الخلية:** تعريف دالة regression_report بتحسب مقاييس التقييم الثلاثة (MAE, RMSE, R2) لأي موديل وتطبعها بشكل واضح وترجعها في dict، ثم استخدامها لتقييم نتائج CatBoost وLightGBM لموديل 1 وتجميعهم في جدول واحد."""

def regression_report(y_true, y_pred, model_name):
    mae = mean_absolute_error(y_true, y_pred)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    r2 = r2_score(y_true, y_pred)

    print(f"--- {model_name} (Model 1: active_power) ---")
    print(f"MAE  : {mae:.3f}")
    print(f"RMSE : {rmse:.3f}")
    print(f"R2   : {r2:.4f}")
    print()

    return {"Model": model_name, "MAE": mae, "RMSE": rmse, "R2": r2}

